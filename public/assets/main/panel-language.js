    const activeTranslations = isEnglish ? translations : indonesianTranslations;
    const textTags = new Set(['A', 'BUTTON', 'H1', 'H2', 'H3', 'H4', 'H5', 'H6', 'INPUT', 'LABEL', 'P', 'SMALL', 'SPAN', 'TH', 'DIV', 'LI']);
    const attributeNames = ['placeholder', 'title', 'aria-label'];

    function translateText(value) {
        const trimmed = value.trim();
        if (Object.prototype.hasOwnProperty.call(activeTranslations, trimmed)) {
            return value.replace(trimmed, activeTranslations[trimmed]);
        }
        return value;
    }

    function updateTextNode(node) {
        const translated = translateText(node.nodeValue);
        if (translated !== node.nodeValue) {
            node.nodeValue = translated;
        }
    }

    function translateAttribute(value) {
        if (activeTranslations[value]) {
            return activeTranslations[value];
        }

        if (isEnglish && value.startsWith('Hadir: ')) {
            return value.replace(/^Hadir: /, 'Present: ');
        }
        if (!isEnglish && value.startsWith('Present: ')) {
            return value.replace(/^Present: /, 'Hadir: ');
        }

        return value;
    }

    function isExcluded(element) {
        return element.closest('script, style, textarea, select, option, tbody, td, .activity-feed, [data-no-translate], [contenteditable="true"]') !== null;
    }

    function translateElement(root) {
        if (!(root instanceof Element) || isExcluded(root)) {
            return;
        }

        [root, ...root.querySelectorAll('*')].forEach((element) => {
            if (textTags.has(element.tagName) && !isExcluded(element)) {
                for (const attributeName of attributeNames) {
                    const value = element.getAttribute(attributeName);
                    if (value) {
                        const translated = translateAttribute(value);
                        if (translated !== value) {
                            element.setAttribute(attributeName, translated);
                        }
                    }
                }
            }
        });

        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            const parent = node.parentElement;
            if (!parent || isExcluded(parent)) {
                continue;
            }

            updateTextNode(node);
        }
    }

    translateElement(document.body);

    const observer = new MutationObserver((mutations) => {
        for (const mutation of mutations) {
            if (mutation.type === 'childList') {
                mutation.addedNodes.forEach((node) => {
                    if (node instanceof Element) {
                        translateElement(node);
                    } else if (node instanceof Text && node.parentElement && !isExcluded(node.parentElement)) {
                        updateTextNode(node);
                    }
                });
            } else if (mutation.type === 'characterData' && mutation.target.parentElement && !isExcluded(mutation.target.parentElement)) {
                updateTextNode(mutation.target);
            }
        }
    });
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
